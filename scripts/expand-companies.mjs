function makeEvidence(company) {
  const sourceType =
    company.primaryJobUrlType === "official_campus" || company.primaryJobUrlType === "official_careers"
      ? company.primaryJobUrlType
      : "third_party_job_board";

  const title =
    company.primaryJobUrlType === "official_campus"
      ? `${company.name}校园招聘`
      : `${company.name}招聘官网`;

  return [
    {
      id: `${company.id}-primary`,
      sourceType,
      title,
      url: company.primaryJobUrl,
      publisher: `${company.name}招聘入口`,
      publishedAt: CAPTURED_AT,
      capturedAt: CAPTURED_AT,
      excerpt: company.description,
      isPrimary: true,
      supportsEmployeeScale: false,
      supportsCampusHiring: true
    }
  ];
}

function finalizeCompany(input) {
  return {
    aliases: [],
    employeeScaleScope: input.employeeScaleScope ?? "global",
    employeeScaleVerified: input.employeeScaleVerified ?? false,
    campusHiringStatus: input.campusHiringStatus ?? "likely_active",
    campusHiringLastSeenAt: input.campusHiringLastSeenAt ?? CAPTURED_AT,
    primaryJobUrlVerified: input.primaryJobUrlVerified ?? false,
    primaryJobUrlVerifiedAt: CAPTURED_AT,
    primaryJobUrlNote:
      input.primaryJobUrlNote ?? "初版批量导入，待人工逐条复核链接稳定性与具体岗位页。",
    notes:
      input.notes ?? "初版批量导入，后续建议补官方中国员工口径与更近的校招证据。",
    tags:
      input.tags ??
      [
        input.primaryJobUrlType === "official_campus" ? "官方校招" : "官方招聘",
        input.industry,
        "待复核"
      ],
    evidence: makeEvidence(input),
    ...input
  };
}

